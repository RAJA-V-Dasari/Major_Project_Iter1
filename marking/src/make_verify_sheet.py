"""
Generate the human verification checklist for the hand-authored rubric.

    keys/cie*.json  ->  keys/VERIFY.md

The rubric was read off the scans by one reader and nothing mechanical
can tell whether a mark was attributed to the right claim. validate_keys
proves the arithmetic; this sheet is what proves the judgement, and it
is generated rather than written so it cannot drift from the keys it
describes. Re-run it after any edit to a key.

It is ordered to be worked through with the PDF open, and it puts the
questions that need the most attention first within each CIE:

  * questions whose split we INFERRED, because there the division into
    items is ours and the examiner never agreed to it
  * every DEFECT and VERIFY note, because those are places where the
    scheme is wrong, illegible, or disagrees with itself
  * short numeric `exact` values, which tier 1 acts on without a model

Run:
    python src/make_verify_sheet.py
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import paths

SHORT_NUMERIC = 3


def collect(key):
    """Pull out the things a verifier should look at hardest."""

    inferred, flagged, shorts = [], [], []

    for spec in key["questions"]:
        qid = spec["id"]

        if spec["breakdown_source"] == "inferred":
            inferred.append(spec)

        for note in spec.get("notes", []):
            if note.startswith(("DEFECT", "NO `exact`")) or "VERIFY" in note:
                flagged.append((qid, spec["scheme_page"], note))

        for item in spec["rubric"]:
            for value in item.get("exact", []):
                if value.strip().isdigit() and len(value.strip()) < SHORT_NUMERIC:
                    shorts.append((qid, value, item["point"]))

    return inferred, flagged, shorts


def render(keys):
    out = []
    add = out.append

    add("# Rubric verification checklist")
    add("")
    add("Generated by `src/make_verify_sheet.py` - do not edit by hand,")
    add("re-run it. Tick a question only once you have compared it against")
    add("the scheme page named beside it.")
    add("")
    add("`validate_keys.py` already proves that every rubric sums to its")
    add("question, that each part matches the total printed on the scheme,")
    add("and that the choice pairs are reciprocal. What it cannot check is")
    add("whether a mark is attached to the right claim. That is this sheet.")
    add("")

    total_q = sum(len(k["questions"]) for k in keys)
    total_i = sum(len(q["rubric"]) for k in keys for q in k["questions"])
    add(f"**{total_q} questions, {total_i} rubric items across "
        f"{len(keys)} schemes.**")
    add("")
    add("---")
    add("")

    for key in keys:
        cie = key["cie"]
        inferred, flagged, shorts = collect(key)

        add(f"## CIE {cie}")
        add("")
        add(f"Source: `{key['source']}`  ")
        add(f"Pages: `keys/scheme_pages/cie{cie}_p*.png`")
        add("")

        for note in key.get("notes", []):
            add(f"> {note}")
            add("")

        # --- the whole question list -----------------------------
        add("| ok | q | page | marks | items | split | needs a look |")
        add("|---|---|---|---|---|---|---|")
        for spec in key["questions"]:
            qid = spec["id"]
            split = ("printed" if spec["breakdown_source"] == "printed"
                     else "**INFERRED**")
            attention = []
            if spec["breakdown_source"] == "inferred":
                attention.append("split is ours")
            if any(n.startswith("DEFECT") for n in spec.get("notes", [])):
                attention.append("**scheme defect**")
            if any("VERIFY" in n for n in spec.get("notes", [])):
                attention.append("illegible/unverified")
            if any(i.get("figure") for i in spec["rubric"]):
                figures = sum(1 for i in spec["rubric"] if i.get("figure"))
                attention.append(f"{figures} figure item(s)")
            add(f"| [ ] | `{qid}` | `{spec['scheme_page']}` | "
                f"{spec['marks']} | {len(spec['rubric'])} | {split} | "
                f"{', '.join(attention) or '-'} |")
        add("")

        # --- inferred splits -------------------------------------
        if inferred:
            add(f"### Inferred splits ({len(inferred)}) - check these first")
            add("")
            add("The scheme gave a total and a solution but no breakdown, so")
            add("the division below is **our judgement, not the**")
            add("**department's**. If you disagree with a split, change it")
            add("here rather than arguing with the grader later - and expect")
            add("these questions to be where we differ from the examiner for")
            add("reasons that are nobody's mistake.")
            add("")
            for spec in inferred:
                add(f"**`{spec['id']}`** ({spec['marks']} marks, "
                    f"`{spec['scheme_page']}`) - {spec['breakdown_text']}")
                add("")
                for item in spec["rubric"]:
                    add(f"- [ ] **{item['marks']}** - {item['point']}")
                add("")

        # --- flagged notes ---------------------------------------
        if flagged:
            add(f"### Flagged ({len(flagged)})")
            add("")
            for qid, page, note in flagged:
                add(f"- [ ] **`{qid}`** (`{page}`) - {note}")
            add("")

        # --- short exacts ----------------------------------------
        if shorts:
            add(f"### Short numeric exact values ({len(shorts)})")
            add("")
            add("Tier 1 acts on these with no model involved. Each one is")
            add("safe only because the item's keywords must match too - a")
            add("bare `88` fires on anything, `88` next to \"length\" does")
            add("not. Confirm each is really an answer and not a number that")
            add("could turn up by chance.")
            add("")
            for qid, value, point in shorts:
                add(f"- [ ] **`{qid}`** `{value}` - {point}")
            add("")

        add("---")
        add("")

    add("## When this sheet is finished")
    add("")
    add("Sign it off here, and the rubric stops being one person's reading")
    add("of a scan and becomes the agreed key:")
    add("")
    add("- [ ] CIE 1 checked against the PDF")
    add("- [ ] CIE 2 checked against the PDF")
    add("- [ ] CIE 3 checked against the PDF")
    add("- [ ] The scheme defects have been raised with the examiner")
    add("")
    add("Checked by: ______________  Date: ____________")

    return "\n".join(out) + "\n"


def main():
    keys = []
    for path in sorted(paths.KEYS_DIR.glob("cie*.json")):
        with open(path, encoding="utf-8") as handle:
            keys.append(json.load(handle))

    if not keys:
        raise SystemExit(f"no keys in {paths.KEYS_DIR}")

    out = paths.KEYS_DIR / "VERIFY.md"
    out.write_text(render(keys), encoding="utf-8")
    print(f"{out}  ({len(keys)} schemes, "
          f"{sum(len(k['questions']) for k in keys)} questions)")


if __name__ == "__main__":
    main()
